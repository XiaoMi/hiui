import fs from 'node:fs/promises'
import path from 'node:path'

export const HIUI_GITIGNORE_BLOCK_START = '# >>> hiui-design managed boundary >>>'
export const HIUI_GITIGNORE_BLOCK_END = '# <<< hiui-design managed boundary <<<'
export const HIUI_GITIGNORE_DISABLE_MARKER = '# hiui-design:disable-managed-gitignore'

async function readTextIfExists(filePath) {
  try {
    return await fs.readFile(filePath, 'utf8')
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return ''
    throw error
  }
}

function normalizeNewline(content) {
  return String(content || '').replace(/\r\n/g, '\n')
}

function buildHiuiGitignoreBoundaryLines({ syncProfile = 'minimal' } = {}) {
  const profile = syncProfile === 'workbench' ? 'workbench' : 'minimal'
  const commonLines = [
    HIUI_GITIGNORE_BLOCK_START,
    '# Generated by hiui-design bootstrap. Remove only if the project owns this boundary elsewhere.',
    '# Keep generated page source, runtime files, docs, light plans, contracts, and acceptance reports reviewable.',
    '.local-context/hiui-design/core/outputs/',
    '.local-context/hiui-design/outputs/*',
    '!.local-context/hiui-design/outputs/runtime-seal.json',
    '!.local-context/hiui-design/outputs/runtime-compatibility-lock.json',
    '!.local-context/hiui-design/outputs/runtime-provider-contract.json',
    '!.local-context/hiui-design/outputs/light-plans/',
    '!.local-context/hiui-design/outputs/light-plans/**',
    '!.local-context/hiui-design/outputs/page-contracts/',
    '!.local-context/hiui-design/outputs/page-contracts/**',
    '!.local-context/hiui-design/outputs/legacy-acceptance/',
    '!.local-context/hiui-design/outputs/legacy-acceptance/**',
    '!.local-context/hiui-design/docs/',
    '!.local-context/hiui-design/docs/**',
  ]
  const minimalOnlyLines = [
    '.local-context/hiui-design/examples/',
    '.local-context/hiui-design/reference/',
    '.local-context/hiui-design/scripts/tests/',
  ]
  return [...commonLines, ...(profile === 'minimal' ? minimalOnlyLines : []), HIUI_GITIGNORE_BLOCK_END]
}

export function buildHiuiGitignoreBoundary(options = {}) {
  return `${buildHiuiGitignoreBoundaryLines(options).join('\n')}\n`
}

export function upsertHiuiGitignoreBoundaryContent(content, options = {}) {
  const normalized = normalizeNewline(content)
  if (normalized.includes(HIUI_GITIGNORE_DISABLE_MARKER)) {
    return { changed: false, content: normalized, skipped: true, reason: 'managed gitignore boundary is disabled' }
  }

  const block = buildHiuiGitignoreBoundary(options).trimEnd()
  const pattern = new RegExp(
    `${HIUI_GITIGNORE_BLOCK_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${HIUI_GITIGNORE_BLOCK_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`,
    'u'
  )
  const trimmed = normalized.trimEnd()
  const nextContent = pattern.test(normalized)
    ? normalized.replace(pattern, block).trimEnd()
    : `${trimmed}${trimmed ? '\n\n' : ''}${block}`

  return {
    changed: `${nextContent}\n` !== normalized,
    content: `${nextContent}\n`,
    skipped: false,
    reason: '',
  }
}

export async function upsertHiuiGitignoreBoundary({ targetRoot, syncProfile = 'minimal' }) {
  const gitignorePath = path.join(targetRoot, '.gitignore')
  const previous = await readTextIfExists(gitignorePath)
  const result = upsertHiuiGitignoreBoundaryContent(previous, { syncProfile })
  if (!result.skipped && result.changed) {
    await fs.writeFile(gitignorePath, result.content, 'utf8')
  }
  return {
    status: result.skipped ? 'skipped' : result.changed ? 'updated' : 'unchanged',
    changed: result.changed,
    path: gitignorePath,
    reason: result.reason,
    syncProfile: syncProfile === 'workbench' ? 'workbench' : 'minimal',
  }
}
